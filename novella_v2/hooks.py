"""Persistent plot hooks linked to the existing open_threads.md arc index.

Every unresolved hook has its own durable row, so updating one promise does
not erase other mysteries or NPC plans. All claims must trace to the author's
original text or a real saved scene. This file is DIRECTOR knowledge, not POV
or NPC knowledge. No plot events are generated by this module.
"""
from __future__ import annotations

import json
import re

HEADER = "# Сюжетные крючки и обязательства\n"
MAX_HOOKS = 4096  # safety ceiling, not a storytelling quota
MAX_CHANGES = 128
IDENT = re.compile(r"^[a-z][a-z0-9_]{1,49}$")
KINDS = {"mystery", "commitment", "appearance", "consequence", "npc_goal", "genre"}
OPEN_STATUSES = {"open", "active", "blocked"}
STATUSES = OPEN_STATUSES | {"closed"}
KEYS = {"id", "arc_id", "title", "kind", "status", "detail", "participants",
        "origin", "origin_turn", "last_evidence", "last_turn",
        "window_start", "window_end", "trigger"}


class HookProblem(ValueError):
    pass


def check(ok: bool, message: str) -> None:
    if not ok:
        raise HookProblem(message)


def short(value: object, length: int, label: str) -> str:
    check(isinstance(value, str) and 0 < len(value.strip()) <= length
          and "\n" not in value and "\r" not in value, "Invalid " + label)
    return value.strip()


def clean(row: dict, cast: set[str] | None = None) -> dict:
    check(isinstance(row, dict) and set(row) == KEYS, "Hook has fixed fields")
    for field in ("id", "arc_id"):
        check(isinstance(row[field], str) and bool(IDENT.fullmatch(row[field])),
              "Invalid " + field)
    check(row["kind"] in KINDS and row["status"] in STATUSES, "Invalid hook kind/status")
    check(type(row["origin_turn"]) is int and row["origin_turn"] >= 0 and
          type(row["last_turn"]) is int and
          row["last_turn"] >= row["origin_turn"], "Invalid hook turn")
    participants = row["participants"]
    check(isinstance(participants, list) and len(participants) == len(set(
        p for p in participants if isinstance(p, str))) and
        all(isinstance(p, str) and IDENT.fullmatch(p) for p in participants) and
        (cast is None or set(participants) <= cast | {"pov"}), "Invalid hook participants")
    for field in ("window_start", "window_end"):
        check(row[field] is None or (type(row[field]) is int and
              row[field] >= 1), "Invalid author window")
    if row["window_start"] is not None and row["window_end"] is not None:
        check(row["window_start"] <= row["window_end"], "Reversed author window")
    if row["window_start"] is not None or row["window_end"] is not None:
        check(row["origin_turn"] == 0 and any(
            w["window_start"] == row["window_start"] and
            w["window_end"] == row["window_end"]
            for w in author_window_candidates(row["origin"], 0)),
            "Turn deadlines require an explicit matching author timing clause")
        if row["kind"] == "appearance":
            check(len(participants) == 1 and participants[0] != "pov",
                  "Track each timed NPC appearance separately")
    if row["status"] == "closed":
        check(row["last_turn"] > 0 and len(row["detail"].strip()) >= 12,
              "Closed hooks need a documented outcome in a real scene")
    return {
        "id": row["id"], "arc_id": row["arc_id"],
        "title": short(row["title"], 140, "title"),
        "kind": row["kind"], "status": row["status"],
        "detail": short(row["detail"], 650, "detail"),
        "participants": sorted(participants),
        "origin": short(row["origin"], 500, "origin quote"),
        "origin_turn": row["origin_turn"],
        "last_evidence": short(row["last_evidence"], 500, "last evidence"),
        "last_turn": row["last_turn"],
        "window_start": row["window_start"], "window_end": row["window_end"],
        "trigger": short(row["trigger"], 300, "trigger") if row["trigger"] is not None else None,
    }


def render(items: list[dict], cast: set[str] | None = None) -> str:
    check(isinstance(items, list) and len(items) <= MAX_HOOKS,
          "Story ledger exceeds safety capacity; preserve all entries and request maintenance")
    rows = [clean(item, cast) for item in items]
    check(len({item["id"] for item in rows}) == len(rows), "Duplicate hook id")
    rows.sort(key=lambda x: (x["arc_id"], x["id"]))
    return HEADER + "".join("- " + json.dumps(row, ensure_ascii=False,
                       sort_keys=True, separators=(",", ":")) + "\n" for row in rows)


def parse(text: str, cast: set[str] | None = None) -> list[dict]:
    check(isinstance(text, str) and text.startswith(HEADER), "Invalid hooks.md header")
    rows = []
    for line in text[len(HEADER):].splitlines():
        check(line.startswith("- "), "Invalid hooks.md line")
        try:
            row = json.loads(line[2:])
        except (ValueError, TypeError) as exc:
            raise HookProblem("Invalid hooks.md JSON") from exc
        rows.append(clean(row, cast))
    check(render(rows, cast) == text, "Noncanonical hooks.md or duplicate IDs")
    return rows


def _proposal(item: dict) -> dict:
    """Public hook change accepts optional canon-window/trigger fields."""
    mandatory = {"id", "arc_id", "title", "kind", "status",
                 "detail", "participants", "source"}
    allowed = mandatory | {"window_start", "window_end", "trigger"}
    check(isinstance(item, dict) and mandatory <= set(item) <= allowed,
          "Hook change needs id/arc_id/title/kind/status/detail/participants/source")
    return {**item, "window_start": item.get("window_start"),
            "window_end": item.get("window_end"), "trigger": item.get("trigger")}


def _new(proposal: dict, origin_turn: int) -> dict:
    return {
        "id": proposal["id"], "arc_id": proposal["arc_id"],
        "title": proposal["title"], "kind": proposal["kind"],
        "status": proposal["status"], "detail": proposal["detail"],
        "participants": proposal["participants"],
        "origin": proposal["source"], "origin_turn": origin_turn,
        "last_evidence": proposal["source"], "last_turn": origin_turn,
        "window_start": proposal["window_start"],
        "window_end": proposal["window_end"], "trigger": proposal["trigger"],
    }


def seed(items: list[dict] | None, original: str,
         cast: set[str]) -> str:
    check(items is None or isinstance(items, list), "Initial hooks must be a list")
    result = []
    for item in items or []:
        row = _proposal(item)
        check(row["status"] in OPEN_STATUSES, "Cannot seed a closed hook")
        check(isinstance(row["source"], str) and
              row["source"] in original and len(row["source"]) >= 8,
              "Initial hook requires exact quote from author original")
        result.append(_new(row, 0))
    return render(result, cast)


def apply(text: str, updates: list[dict], narration: str, turn: int,
          cast: set[str]) -> tuple[str, list[dict]]:
    before = {row["id"]: row for row in parse(text, cast)}
    check(isinstance(updates, list) and len(updates) <= MAX_CHANGES,
          "Too many hooks changed in one scene")
    check(len({x.get("id") for x in updates if isinstance(x, dict)}) == len(updates),
          "Hook updated twice")
    result = []
    for item in updates:
        row = _proposal(item)
        check(isinstance(row["source"], str) and
              8 <= len(row["source"]) <= 500 and row["source"] in narration,
              "Hook change needs exact excerpt from the final scene")
        old = before.get(row["id"])
        if old is None:
            check(row["status"] != "closed", "Cannot close unknown hook")
            new = _new(row, turn)
        else:
            for field in ("arc_id", "title", "kind"):
                check(row[field] == old[field], "Hook identity cannot change")
            check(old["status"] != "closed" or row["status"] != "closed",
                  "Already closed hook cannot be closed again")
            if old["kind"] == "appearance":
                check(sorted(row["participants"]) == old["participants"],
                      "Appearance obligation cannot change its NPC")
            for field in ("window_start", "window_end"):
                check(row[field] in (None, old[field]),
                      "Cannot rewrite author deadline")
            changed = (row["status"] != old["status"] or
                       row["detail"].strip() != old["detail"] or
                       sorted(row["participants"]) != old["participants"] or
                       row["trigger"] != old["trigger"])
            check(changed, "Hook needs real status/content/actor/trigger progress; "
                  "a new turn or quote alone cannot reset its age")
            new = {**old, "status": row["status"], "detail": row["detail"],
                   "participants": row["participants"], "trigger": row["trigger"],
                   "last_evidence": row["source"], "last_turn": turn}
        if row["status"] == "closed":
            check(len(row["detail"].strip()) >= 12 and
                  row["detail"].strip() != old["detail"],
                  "Closure requires an explicit, changed outcome")
        before[row["id"]] = clean(new, cast)
        result.append(item)
    return render(list(before.values()), cast), result


def backfill(text: str, additions: list[dict], original: str,
             scenes: dict[int, str], current_turn: int,
             cast: set[str]) -> str:
    """Add only proven missed hooks without rewriting historical scenes."""
    current = {row["id"]: row for row in parse(text, cast)}
    check(isinstance(additions, list) and len(additions) <= MAX_HOOKS,
          "Invalid backfill size")
    for item in additions:
        check(isinstance(item, dict) and "origin_turn" in item and
              set(item) <= {"id", "arc_id", "title", "kind", "status",
                            "detail", "participants", "source",
                            "window_start", "window_end", "trigger", "origin_turn",
                            "last_turn", "last_evidence", "reopen", "reconcile"},
              "Backfill requires origin_turn and a complete hook proposal")
        quote_turn = item["origin_turn"]
        check(type(quote_turn) is int and 0 <= quote_turn <= current_turn,
              "Invalid backfill source turn")
        row = _proposal({k: v for k, v in item.items()
                         if k not in {"origin_turn", "last_turn", "last_evidence", "reopen", "reconcile"}})
        existing = current.get(row["id"])
        reopen = item.get("reopen", False)
        reconcile = item.get("reconcile", False)
        check(type(reopen) is bool and type(reconcile) is bool and
              not (reopen and reconcile) and (
              existing is None and not reopen and not reconcile or
              existing is not None and existing["status"] == "closed" and
              reopen and row["status"] in OPEN_STATUSES or
              existing is not None and reconcile and
              existing["status"] in OPEN_STATUSES and row["status"] == "closed"),
              "Backfill may add new hooks, explicitly reopen or reconcile a historical closure")
        source = original if quote_turn == 0 else scenes.get(quote_turn, "")
        check(isinstance(row["source"], str) and
              len(row["source"]) >= 8 and row["source"] in source,
              "Backfill quote must exist in original or exact saved scene")
        last_turn = item.get("last_turn", quote_turn)
        if last_turn is None:
            last_turn = quote_turn
        last_evidence = item.get("last_evidence") or row["source"]
        check(type(last_turn) is int and quote_turn <= last_turn <= current_turn,
              "Invalid last development turn")
        latest = original if last_turn == 0 else scenes.get(last_turn, "")
        check(isinstance(last_evidence, str) and 8 <= len(last_evidence) <= 500 and
              last_evidence in latest, "Last development requires its own exact quote")
        entry = {**_new(row, quote_turn), "last_turn": last_turn,
                 "last_evidence": last_evidence}
        if existing is not None:
            for field in ("arc_id", "title", "kind", "origin", "origin_turn",
                          "window_start", "window_end"):
                check(entry[field] == existing[field],
                      "Reopening must preserve the original hook identity and source")
            if existing["kind"] == "appearance":
                check(entry["participants"] == existing["participants"],
                      "Reopening cannot change the NPC of an appearance obligation")
        current[row["id"]] = clean(entry, cast)
    return render(list(current.values()), cast)


_AUTHOR_RANGE = re.compile(
    r"(?iu)(?<!\d)(\d{1,5})\s*(?:-(?:м|й|го|ого|му))?\s*"
    r"(?:и|по|до|[-–—])\s*"
    r"(\d{1,5})\s*(?:-(?:м|й|го|ого|му))?\s*ход"
)
_AUTHOR_UP_TO = re.compile(
    r"(?iu)\bдо\s+(\d{1,5})\s*(?:-(?:м|й|го|ого|му))?\s*ход"
)
_AUTHOR_ENTRY = re.compile(r"(?iu)появ|ввод|войти|войд|приход|встреч|долж|обяз")


def author_window_candidates(original: str, turn: int) -> list[dict]:
    """Extract literal author deadline mentions even in legacy sessions.

    Hints are NEVER automatically saved as hooks or used to fake an
    event. The director reviews quoted text before adding a verified
    sourced hook. A sentence with no explicit bound is not a deadline.
    """
    if not isinstance(original, str):
        return []
    candidates: list[dict] = []
    for line_no, raw in enumerate(original.splitlines(), start=1):
        line = raw.strip()
        if not _AUTHOR_ENTRY.search(line) or "ход" not in line.casefold():
            continue
        ranges = list(_AUTHOR_RANGE.finditer(line))
        windows = [(int(m.group(1)), int(m.group(2)), m) for m in ranges]
        windows.extend(
            (None, int(m.group(1)), m)
            for m in _AUTHOR_UP_TO.finditer(line)
            if not any(start.start() <= m.start() < start.end()
                       for start in ranges)
        )
        for lower, upper, match in windows:
            if upper < 1 or (lower is not None and lower > upper):
                continue
            # Long one-line questionnaires often list several different
            # characters in a single paragraph. Quote the local matched
            # clause instead of chopping the original line at 500 chars.
            start = max(0, match.start() - 110)
            stop = min(len(line), match.end() + 140)
            excerpt = line[start:stop]
            candidates.append({
                "id": f"window:{line_no}:{match.start()}",
                "source_line": line_no, "source": excerpt,
                "window_start": lower, "window_end": upper,
                "window_elapsed": turn + 1 > upper,
                "overdue": turn + 1 > upper,  # compatibility: only elapsed, not verified failure
            })
    return candidates


def director_brief(items: list[dict], turn: int) -> dict:
    """Compact planning index. Closed obligations remain permanently recorded."""
    upcoming = turn + 1
    rows, closed = [], []
    for item in items:
        deadline = item["window_end"]
        state = "awaiting_condition" if item["status"] == "blocked" and item["trigger"] else "none"
        if item["status"] == "closed":
            if deadline is not None:
                state = ("fulfilled_late" if item["last_turn"] > deadline else
                         "fulfilled_early" if item["window_start"] is not None and
                         item["last_turn"] < item["window_start"] else "fulfilled")
            else:
                state = "resolved"
            closed.append({**item, "deadline_state": state})
            continue
        if deadline is not None:
            if deadline < upcoming:
                state = "overdue"
            elif item["window_start"] is None or item["window_start"] <= upcoming:
                state = "author_window_open"
            else:
                state = "author_window_future"
        rows.append({**item, "deadline_state": state,
                     "turns_since_progress": max(0, turn - item["last_turn"])})
    rows.sort(key=lambda x: (x["deadline_state"] != "overdue",
              x["deadline_state"] != "author_window_open",
              -x["turns_since_progress"], x["arc_id"], x["id"]))
    return {
        "upcoming_turn": upcoming,
        "unresolved_hooks": rows,
        "resolved_hooks": closed,
        "author_deadlines_overdue": [x["id"] for x in rows if x["deadline_state"] == "overdue"],
        "author_windows_active": [x["id"] for x in rows if x["deadline_state"] == "author_window_open"],
        "stale_hooks": [x["id"] for x in rows if x["turns_since_progress"] >= 20
                        and x["status"] != "blocked"
                        and x["deadline_state"] != "author_window_future"],
        "note": ("Director-only facts. Staleness is a diagnostic, not a quota. "
                 "Never invent retroactive scenes or force arbitrary appearances."),
    }
